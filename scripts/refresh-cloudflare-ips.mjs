#!/usr/bin/env node
// Refresh src/lib/cloudflare-ip-ranges.data.ts from Cloudflare's published lists.
// Usage: node scripts/refresh-cloudflare-ips.mjs
// Then commit the data file. The Hetzner firewall allowlist is separate.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const V4_URL = "https://www.cloudflare.com/ips-v4";
const V6_URL = "https://www.cloudflare.com/ips-v6";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "src", "lib", "cloudflare-ip-ranges.data.ts");

function parseList(body, family) {
  const lines = body
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("#"));
  const cidrRe = family === 4
    ? /^\d{1,3}(?:\.\d{1,3}){3}\/\d{1,2}$/
    : /^[0-9a-fA-F:]+\/\d{1,3}$/;
  for (const line of lines) {
    if (!cidrRe.test(line)) {
      throw new Error(`Unexpected ${family === 4 ? "IPv4" : "IPv6"} CIDR from Cloudflare: ${line}`);
    }
  }
  if (lines.length === 0) {
    throw new Error(`Cloudflare returned no ${family === 4 ? "IPv4" : "IPv6"} ranges`);
  }
  return [...lines].sort((a, b) => a.localeCompare(b));
}

async function fetchText(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`GET ${url} failed with HTTP ${response.status}`);
  }
  return response.text();
}

const retrieved = new Date().toISOString().slice(0, 10);
const [v4body, v6body] = await Promise.all([fetchText(V4_URL), fetchText(V6_URL)]);
const v4 = parseList(v4body, 4);
const v6 = parseList(v6body, 6);

function arrayLiteral(cidrs) {
  return cidrs.map((cidr) => `  "${cidr}"`).join(",\n");
}

const source = `// Generated by scripts/refresh-cloudflare-ips.mjs
// Source: https://www.cloudflare.com/ips-v4 and https://www.cloudflare.com/ips-v6
// Retrieved: ${retrieved}
// Do not edit by hand. Re-run the script to refresh.

export const CLOUDFLARE_IP_RANGES_RETRIEVED = "${retrieved}";

export const CLOUDFLARE_IPV4_CIDRS = [
${arrayLiteral(v4)}
] as const;

export const CLOUDFLARE_IPV6_CIDRS = [
${arrayLiteral(v6)}
] as const;
`;

writeFileSync(outPath, source, "utf8");
process.stdout.write(`Wrote ${v4.length} IPv4 and ${v6.length} IPv6 ranges (${retrieved}) to ${outPath}\n`);
